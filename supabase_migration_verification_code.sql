-- Email Verification Code Migration
-- Adds 4-digit verification code to users table
-- ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

ALTER TABLE public.users
  ADD COLUMN IF NOT EXISTS verification_code  TEXT,
  ADD COLUMN IF NOT EXISTS code_expires_at    TIMESTAMPTZ;

-- ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
-- Column Descriptions:
-- ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
--
-- verification_code:  4-digit code sent via email for account verification
-- code_expires_at:    Expiration timestamp for the verification code (15 minutes)
--
-- ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

-- Verify the migration
SELECT column_name, data_type
FROM information_schema.columns
WHERE table_name = 'users'
  AND column_name IN ('verification_code', 'code_expires_at')
ORDER BY column_name;
